# -*- coding: utf-8 -*-
"""Чистые функции: считают из аргументов, без сети и без базы.

Сюда попадает всё, где ошибка тихая. Классификатор целей вдвое занижал конверсии
и никто этого не видел месяцами; разбор чисел из Директа ломается на пробелах
внутри числа; допуск при перерасходе легко перепутать с порогом показа.
Такое ловится дешевле всего и должно ловиться до выката, а не после.
"""
import statistics

import pytest

from iigbot import report
from iigbot.api import Api


# ─────────────────── классификатор целей ───────────────────
# Тот самый баг: приставка «Автоцель» — это метка Яндекса, а не суть цели.
# Из-за неё «Автоцель: отправка формы» считалась поведением, а не обращением,
# и половина конверсий уходила мимо отчёта.
@pytest.mark.parametrize("имя", [
    "Отправка формы",
    "Автоцель: отправка формы",
    "Клик по номеру телефона",
    "Автоцель: клик по номеру телефона",
    "Заказ обратного звонка",
    "Клик по кнопке Позвонить",
    "Написали в WhatsApp",
    "Отправлена заявка",
])
def test_обращения_распознаются(имя):
    assert Api._goal_kind(имя) == "contact", имя


@pytest.mark.parametrize("имя", [
    "Просмотр 3 страниц",
    "Автоцель: просмотр 3 страниц",
    "Время на сайте больше 30 секунд",
    "Прокрутка до конца страницы",
    "Автоцель: прокрутка",
])
def test_поведение_не_считается_обращением(имя):
    assert Api._goal_kind(имя) != "contact", имя


def test_приставка_автоцель_ничего_не_меняет():
    """Ровно тот случай, из-за которого конверсии занижались вдвое."""
    for имя in ("отправка формы", "клик по номеру телефона", "заказ звонка"):
        без = Api._goal_kind(имя)
        с_меткой = Api._goal_kind("Автоцель: " + имя)
        assert без == с_меткой, "метка Яндекса изменила смысл цели: " + имя


def test_слово_кнопка_не_перебивает_позвонить():
    """Порядок проверок был такой, что «кнопка» выигрывала у «позвонить»."""
    assert Api._goal_kind("Клик по кнопке Позвонить") == "contact"


# ─────────────────── разбор чисел из Директа ───────────────────
@pytest.mark.parametrize("сырое,ждём", [
    ("123", 123.0),
    ("1 234", 1234.0),          # Директ отдаёт с неразрывными пробелами
    ("1 234", 1234.0),
    ("12,5", 12.5),             # запятая как десятичный разделитель
    ("12.5", 12.5),
    ("--", 0.0),
    ("", 0.0),
    (None, 0.0),
    ("0", 0.0),
])
def test_числа_из_отчёта(сырое, ждём):
    assert report.parse_num(сырое) == pytest.approx(ждём)


def test_число_не_падает_на_мусоре():
    """Отчёт Директа не должен ронять сборку из-за одной кривой ячейки."""
    for мусор in ("нет данных", "N/A", "—", "abc"):
        assert report.parse_num(мусор) == 0.0


# ─────────────────── перерасход: допуск против порога ───────────────────
def превышение(лимит, допуск_процентов, факт):
    """Формула из exp_overspend, вынесенная как есть.

    Допуск — это BudgetIncreasePercent, который Директ разрешает сам.
    Порог показа (15%) к расчёту отношения не имеет: он решает, показывать
    строку или нет, а не сколько процентов перерасхода.
    """
    разрешено = лимит * (1 + допуск_процентов / 100.0)
    return (факт - разрешено) / разрешено * 100


def test_факт_равен_разрешённому_значит_ноль():
    assert превышение(10000, 20, 12000) == pytest.approx(0)


def test_допуск_учитывается_а_не_игнорируется():
    """Без учёта допуска те же цифры дали бы +20% перерасхода вместо нуля."""
    assert превышение(10000, 20, 12000) == pytest.approx(0)
    без_допуска = (12000 - 10000) / 10000 * 100
    assert без_допуска == pytest.approx(20)


def test_недобор_даёт_отрицательное():
    """Не дойти до лимита — это минус, и это НЕ достижение.

    Из-за этого «лучшим» по показателю оказывался остановленный аккаунт,
    и показатель пришлось сделать односторонним.
    """
    assert превышение(10000, 0, 100) < -98


def test_реальный_случай_simplefoods():
    """27 300 ₽ при лимите 16 000 и допуске 0 — это +70%, как и было в жизни."""
    assert превышение(16000, 0, 27300) == pytest.approx(70.6, abs=0.5)


# ─────────────────── медиана бенчмарка ───────────────────
def test_медиана_не_ведётся_на_выброс():
    """Смысл медианы здесь: один дорогой аккаунт не должен сам себя оправдывать."""
    цены = [20, 22, 25, 27, 3000]
    assert statistics.median(цены) == 25
    assert statistics.mean(цены) > 600


def test_отношение_к_медиане():
    цены = [20, 22, 25, 27, 3000]
    med = statistics.median(цены)
    assert round(3000 / med, 1) == 120.0
    assert round(20 / med, 1) == 0.8


def test_медиана_из_двух_значений():
    """Граничный случай: у эталона всего два проекта."""
    assert statistics.median([10, 20]) == 15


# ─────────────────── направления показателей доски ───────────────────
def test_направления_показателей_не_перепутаны():
    """Для цены клика меньше лучше, для кликабельности больше. Перепутать легко."""
    m = {x["key"]: x for x in Api.EXP_METRICS}
    assert m["cpc_x"]["dir"] == -1
    assert m["ctr_x"]["dir"] == 1
    assert m["auto_pct"]["dir"] == -1
    assert m["std_issues"]["dir"] == -1
    assert m["spike_x"]["dir"] == -1
    assert m["over_pct"]["dir"] == -1


def test_превышение_лимита_помечено_односторонним():
    """Если метку снимут, «лучшим» снова станет остановленный аккаунт."""
    m = {x["key"]: x for x in Api.EXP_METRICS}
    assert m["over_pct"].get("one_sided") is True
    assert not any(x.get("one_sided") for k, x in m.items() if k != "over_pct")
